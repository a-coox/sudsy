//! Repository automation. `cargo xtask codegen` regenerates checked-in files from
//! the grammars, the language providers, the JSON Schema of the config and the reference tables
//! of the docs; `cargo xtask codegen --check` (and the `codegen_is_fresh` test)
//! fails when they are stale.

mod docs;
mod new_rule;
mod vscode;

pub use new_rule::new_rule;

use anyhow::{Context, Result, ensure};
use core_syntax::{Grammar, LanguageId, codegen};
use provider_api::LanguageProvider;
use std::path::{Path, PathBuf};

pub fn repo_root() -> PathBuf {
    Path::new(env!("CARGO_MANIFEST_DIR"))
        .parent()
        .expect("xtask lives in the repo root")
        .to_path_buf()
}

/// Every generated file as (path relative to the repo root, contents).
pub fn generate() -> Result<Vec<(PathBuf, String)>> {
    let root = repo_root();
    let providers = languages::providers();
    let mut files: Vec<(PathBuf, String)> = vec![(
        "schemas/sudsy.schema.json".into(),
        config_schema(&providers)?,
    )];
    let mut registry = Vec::new();
    for entry in std::fs::read_dir(root.join("grammars"))? {
        let path = entry?.path();
        let Some(name) = path
            .file_stem()
            .and_then(|n| n.to_str())
            .filter(|_| path.extension().is_some_and(|e| e == "grammar"))
        else {
            continue;
        };
        let src = std::fs::read_to_string(&path)
            .with_context(|| format!("reading {}", path.display()))?;
        let grammar =
            Grammar::parse(&src).with_context(|| format!("parsing {}", path.display()))?;
        let rel = format!("grammars/{name}.grammar");
        files.push((
            format!("crates/lang-{name}/src/generated.rs").into(),
            codegen::rust_module(&grammar, &rel, "core_syntax")?,
        ));
        if name == "csharp" {
            files.push((
                "workers/csharp/Sudsy.Worker/Generated/CsharpGrammar.g.cs".into(),
                codegen::csharp_constants(&grammar, &rel)?,
            ));
        }
        registry.push((name.to_string(), grammar.language_id));
    }
    registry.sort();
    let mut ids: Vec<LanguageId> = registry.iter().map(|(_, id)| *id).collect();
    ids.sort();
    ids.dedup();
    ensure!(
        ids.len() == registry.len(),
        "two grammars share a language id"
    );
    files.push((
        "crates/core-syntax/src/grammars/registry.rs".into(),
        grammar_registry(&registry),
    ));
    files.extend(vscode::generate(&providers)?);
    files.extend(docs::generate(&providers)?);
    Ok(files)
}

/// `core_syntax::grammars`: one loader per grammar file and the lookup by language name.
fn grammar_registry(grammars: &[(String, LanguageId)]) -> String {
    let mut out = String::from(
        "// @generated by `cargo xtask codegen` from grammars/*.grammar. Do not edit.\n\
         use super::load;\nuse crate::Grammar;\nuse std::sync::OnceLock;\n",
    );
    for (name, _) in grammars {
        out += &format!(
            "\npub fn {name}() -> &'static Grammar {{\n    \
             static G: OnceLock<Grammar> = OnceLock::new();\n    \
             load(&G, include_str!(\"../../../../grammars/{name}.grammar\"))\n}}\n"
        );
    }
    let names: Vec<&str> = grammars.iter().map(|(n, _)| n.as_str()).collect();
    out + &format!(
        "\n/// The built-in grammar of `language` (its `language` line), if there is one.\n\
         pub fn by_name(language: &str) -> Option<&'static Grammar> {{\n    \
         [{}]\n        .into_iter()\n        .map(|g| g())\n        .find(|g| g.language == language)\n}}\n",
        names.join(", ")
    )
}

/// The JSON Schema of `sudsy.yaml`, from the option declarations of the providers; editors register it for completion and validation of the config.
fn config_schema(providers: &[Box<dyn LanguageProvider>]) -> Result<String> {
    let schema = core_config::json_schema(
        &languages::schemas(providers),
        &languages::rule_schemas(providers),
    );
    Ok(serde_json::to_string_pretty(&schema)? + "\n")
}

/// Paths of generated files whose checked-in content differs from fresh output.
pub fn stale_files() -> Result<Vec<PathBuf>> {
    let root = repo_root();
    Ok(generate()?
        .into_iter()
        .filter(|(rel, content)| {
            std::fs::read_to_string(root.join(rel)).ok().as_deref() != Some(content)
        })
        .map(|(rel, _)| rel)
        .collect())
}

pub fn write_generated() -> Result<()> {
    let root = repo_root();
    for (rel, content) in generate()? {
        let path = root.join(&rel);
        std::fs::create_dir_all(path.parent().expect("file has a parent"))?;
        std::fs::write(&path, content)?;
        println!("wrote {}", rel.display());
    }
    Ok(())
}
