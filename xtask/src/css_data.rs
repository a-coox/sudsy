//! `cargo xtask css-data <dir>`: the table of known CSS names (`crates/lang-css/data/names.txt`) from the
//! npm packages `known-css-properties` and `mdn-data` installed in `<dir>` (`npm i known-css-properties
//! mdn-data`). Pinned and refreshed deliberately: the table is checked in, so builds and
//! `codegen --check` need no network. `extras.txt` next to it holds what these sources lack.

use anyhow::{Context, Result};
use serde_json::Value;
use std::collections::BTreeSet;
use std::path::Path;

fn json(dir: &Path, file: &str) -> Result<Value> {
    let path = dir.join("node_modules").join(file);
    let text =
        std::fs::read_to_string(&path).with_context(|| format!("reading {}", path.display()))?;
    Ok(serde_json::from_str(&text)?)
}

/// The keys of an object, or the strings of an array.
fn names(v: &Value) -> Vec<&str> {
    match v {
        Value::Object(o) => o.keys().map(String::as_str).collect(),
        Value::Array(a) => a.iter().filter_map(Value::as_str).collect(),
        _ => Vec::new(),
    }
}

/// `@media`, `::before` and `:is()` are `media`, `before` and `is`.
fn plain(name: &str) -> String {
    let lower = name.to_ascii_lowercase();
    let base = lower.trim_start_matches(['@', ':']);
    base.split('(').next().unwrap_or("").to_string()
}

pub fn generate(dir: &Path) -> Result<String> {
    let version = |p: &str| -> Result<String> {
        let v = json(dir, &format!("{p}/package.json"))?;
        Ok(format!("{p} {}", v["version"].as_str().unwrap_or("?")))
    };
    let mdn = |f: &str| json(dir, &format!("mdn-data/css/{f}.json"));
    let kcp = json(dir, "known-css-properties/data/all.json")?;
    let properties = mdn("properties")?;
    let selectors = mdn("selectors")?;
    let (elements, classes): (Vec<_>, Vec<_>) = names(&selectors)
        .into_iter()
        .filter(|n| n.starts_with(':'))
        .partition(|n| n.starts_with("::"));
    let at_rules = mdn("at-rules")?;
    let units = mdn("units")?;
    let functions = mdn("functions")?;
    // known-css-properties also lists the descriptors of `@font-face` and the like.
    let mut property = names(&kcp["properties"]);
    let descriptors: Vec<&str> = at_rules
        .as_object()
        .into_iter()
        .flatten()
        .flat_map(|(_, at)| names(&at["descriptors"]))
        .filter(|d| properties.get(*d).is_none())
        .collect();
    property.retain(|p| !descriptors.contains(p));
    property.extend(names(&properties));
    let sections = [
        ("property", property),
        ("at-rule", names(&at_rules)),
        ("unit", names(&units)),
        ("function", names(&functions)),
        ("pseudo-class", classes),
        ("pseudo-element", elements),
    ];
    let mut out = format!(
        "# Generated by `cargo xtask css-data` from {} (MIT) and {} (CC0-1.0): lowercase names without vendor prefixes.\n",
        version("known-css-properties")?,
        version("mdn-data")?
    );
    for (section, items) in sections {
        // Prefixed names and custom properties are not entries: the rules skip them.
        let set: BTreeSet<String> = items
            .into_iter()
            .map(plain)
            .filter(|n| !n.is_empty() && !n.starts_with('-'))
            .collect();
        out.push_str(&format!("[{section}]\n"));
        let mut line = String::new();
        for name in set {
            if line.len() + name.len() > 100 {
                out.push_str(line.trim_end());
                out.push('\n');
                line.clear();
            }
            line.push_str(&name);
            line.push(' ');
        }
        out.push_str(line.trim_end());
        out.push('\n');
    }
    Ok(out)
}
