// Regenerates `elements.txt` from the element metadata of html-validate (MIT):
//   node crates/lang-html/data/generate.mjs <dir with node_modules/html-validate> > crates/lang-html/data/elements.txt
import { createRequire } from "node:module";
const { HtmlValidate } = createRequire(process.argv[2] + "/")("html-validate");
const pkg = createRequire(process.argv[2] + "/")("html-validate/package.json");

const config = await new HtmlValidate({ root: true }).getConfigFor("a.html");
const elements = config.metaTable.elements;
const names = Object.keys(elements).filter((n) => !n.includes(":")).sort();

// An attribute that more elements have than this is global: its flag is written without an element.
const GLOBAL = 100;
const have = {};
for (const n of names) for (const a of Object.keys(elements[n].attributes ?? {})) (have[a] ??= []).push(n);

const flagged = (test) => {
  const out = new Set();
  for (const [attr, owners] of Object.entries(have)) {
    const on = owners.filter((n) => test(elements[n].attributes[attr]));
    if (on.length === 0) continue;
    if (on.length === owners.length && owners.length > GLOBAL) out.add(attr);
    else for (const n of on) out.add(`${n}:${attr}`);
  }
  return [...out].sort();
};
const values = (a) => (Array.isArray(a.enum) && a.enum.every((v) => typeof v === "string") ? a.enum : null);
const enums = [];
for (const [attr, owners] of Object.entries(have)) {
  const groups = new Map();
  for (const n of owners) {
    const v = values(elements[n].attributes[attr]);
    if (v) (groups.get(v.join("|")) ?? groups.set(v.join("|"), []).get(v.join("|"))).push(n);
  }
  for (const [list, on] of groups) enums.push(on.length > GLOBAL ? `${attr}=${list}` : `${on.join(",")}:${attr}=${list}`);
}

const sections = {
  elements: names,
  void: names.filter((n) => elements[n].void),
  deprecated: names.filter((n) => elements[n].deprecated),
  foreign: names.filter((n) => elements[n].foreign),
  boolean: flagged((a) => a.boolean),
  omit: flagged((a) => a.omit),
  "deprecated-attr": flagged((a) => a.deprecated),
  required: flagged((a) => a.required === true),
  reference: flagged((a) => a.reference === "id"),
  enum: enums.sort(),
};
console.log(`# Generated by generate.mjs from the element metadata of html-validate ${pkg.version} (MIT): lowercase names; \`element:attribute\` is an attribute of one element, a bare name is global; \`[enum]\` is \`[elements:]attribute=value|value\`.`);
for (const [name, list] of Object.entries(sections)) {
  console.log(`[${name}]`);
  let line = "";
  for (const item of list) {
    if (line.length + item.length > 98) { console.log(line.trim()); line = ""; }
    line += item + " ";
  }
  if (line) console.log(line.trim());
}
